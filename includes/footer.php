  <script>
  (function() {
    var btn     = document.getElementById('mobMenuBtn');
    var drawer  = document.getElementById('mobDrawer');
    var overlay = document.getElementById('mobOverlay');
    var closeBtn= document.getElementById('mobDrawerClose');

    function openDrawer() {
      drawer.classList.add('open');
      overlay.classList.add('open');
      document.body.style.overflow = 'hidden';
    }
    function closeDrawer() {
      drawer.classList.remove('open');
      overlay.classList.remove('open');
      document.body.style.overflow = '';
    }

    if (btn)      btn.addEventListener('click', openDrawer);
    if (closeBtn) closeBtn.addEventListener('click', closeDrawer);
    if (overlay)  overlay.addEventListener('click', closeDrawer);

    // ESC tuşu ile kapat
    document.addEventListener('keydown', function(e) {
      if (e.key === 'Escape') closeDrawer();
    });

    // Aktif sayfa vurgulama (alt nav)
    var path = window.location.pathname.split('/').pop() || 'anasayfa.html';
    var map  = {
      'anasayfa.html': 'mbn-home',
      'arama.html':    'mbn-search',
      'favoriler.html':'mbn-fav',
      'sepet.html':    'mbn-cart',
      'hesabim.html':  'mbn-account'
    };
    var activeId = map[path];
    if (activeId) {
      var el = document.getElementById(activeId);
      if (el) el.classList.add('active');
    }

    // Sepet & favori badge senkronizasyonu
    function syncMobBadges() {
      try {
        var cart = JSON.parse(localStorage.getItem('modaica_cart') || '[]');
        var qty  = cart.reduce(function(s, i) { return s + (i.qty || 1); }, 0);
        var cb   = document.getElementById('mbn-cart-badge');
        if (cb) { cb.textContent = qty > 0 ? (qty > 99 ? '99+' : qty) : ''; cb.style.display = qty > 0 ? 'flex' : 'none'; }
      } catch(e) {}

      try {
        var favs = JSON.parse(localStorage.getItem('modaica_favorites') || '[]');
        var fb   = document.getElementById('mbn-fav-badge');
        if (fb) { fb.textContent = favs.length > 0 ? favs.length : ''; fb.style.display = favs.length > 0 ? 'flex' : 'none'; }
      } catch(e) {}
    }

    syncMobBadges();
    window.addEventListener('storage', syncMobBadges);
    // api-client.js updateBadges çağrısından sonra da güncelle
    document.addEventListener('modaica:badges', syncMobBadges);
  })();
  </script>

